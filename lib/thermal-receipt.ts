import type { Business, Sale } from "./types";
import { money } from "./utils";
import { amountReceivedAtSale, creditSaleBalance } from "./customer-accounts";

export type ThermalPaper = "58mm" | "80mm";

// Portable ESC/POS printers differ in their code pages. ASCII is predictable;
// PDFs retain the original spelling. Never allow receipt text to inject commands.
export function printerText(value: string) {
  return value.normalize("NFKD").replace(/[\u0300-\u036f]/g, "")
    .replace(/[‘’]/g, "'").replace(/[“”]/g, '"')
    .replace(/[–—]/g, "-").replace(/×/g, "x")
    .replace(/[^\x20-\x7e]/g, " ").replace(/ +/g, " ").trim();
}

export function wrapPrinterText(value: string, width: number): string[] {
  const text = printerText(value);
  if (!text) return [];
  const lines: string[] = [];
  let line = "";
  for (let word of text.split(" ")) {
    if (line && line.length + word.length + 1 > width) {
      lines.push(line);
      line = "";
    }
    while (word.length > width) {
      lines.push(word.slice(0, width));
      word = word.slice(width);
    }
    if (word) line = line ? `${line} ${word}` : word;
  }
  if (line) lines.push(line);
  return lines;
}

export function receiptText(business: Business, sale: Sale, paper: ThermalPaper) {
  const width = paper === "58mm" ? 32 : 48;
  const lines: string[] = [];
  const add = (text: string) => lines.push(...wrapPrinterText(text, width));
  const pair = (label: string, value: string) => {
    label = printerText(label);
    value = printerText(value);
    if (label.length + value.length + 1 <= width) {
      lines.push(label + " ".repeat(width - label.length - value.length) + value);
    } else {
      add(label);
      for (const part of wrapPrinterText(value, width)) lines.push(part.padStart(width));
    }
  };
  const rule = () => lines.push("-".repeat(width));
  add(business.name);
  add(business.address || business.country);
  if (business.phone) add(business.phone);
  if (business.email) add(business.email);
  rule();
  add(`SALE RECEIPT - ${sale.status.toUpperCase()}`);
  add(`Receipt: ${sale.receiptNo}`);
  const date = new Date(sale.createdAt);
  add(`Date: ${Number.isNaN(date.getTime()) ? sale.createdAt : date.toLocaleString("en-GB")}`);
  add(`Cashier: ${sale.cashier || "Shop owner"}`);
  add(`Customer: ${sale.customerName || "Walk-in customer"}`);
  rule();
  for (const item of sale.items) {
    add(`${item.name}${item.negotiated ? " [N]" : ""}`);
    pair(`${item.qty} x ${money(item.price, business.currency)}`,
      money((item.price - item.discount) * item.qty, business.currency));
    if (item.discount) add(`Item discount: ${money(item.discount * item.qty, business.currency)}`);
  }
  if (sale.items.some((item) => item.negotiated)) add("[N] Negotiated price approved");
  rule();
  pair("Subtotal", money(sale.subtotal, business.currency));
  pair("Discount", `-${money(sale.discount, business.currency)}`);
  pair("Tax", money(sale.tax, business.currency));
  pair("TOTAL", money(sale.total, business.currency));
  rule();
  pair("Payment", sale.payment);
  pair("Received", money(amountReceivedAtSale(sale), business.currency));
  pair(sale.payment === "Customer Credit" ? "Added to account" : "Change", money(sale.payment === "Customer Credit" ? creditSaleBalance(sale) : sale.change, business.currency));
  if (sale.note) add(`Note: ${sale.note}`);
  rule();
  add(business.receiptFooter);
  if (!/powered by nilestock/i.test(business.receiptFooter)) add("Powered by NileStock");
  return lines.join("\n") + "\n";
}

export function escposBytes(text: string) {
  // Reset, font A, normal size, left align, then text + feed. No cash-drawer
  // pulse or cutter: portable printers often have neither.
  // Preserve alignment spaces generated by receiptText, while removing controls.
  const safe = text.split("\n").map((line) =>
    /^[\x20-\x7e]*$/.test(line) ? line : printerText(line),
  ).join("\n");
  const header = [0x1b, 0x40, 0x1b, 0x4d, 0, 0x1d, 0x21, 0, 0x1b, 0x61, 0];
  const body = new TextEncoder().encode(safe);
  const bytes = new Uint8Array(header.length + body.length + 3);
  bytes.set(header);
  bytes.set(body, header.length);
  bytes.fill(10, header.length + body.length);
  return bytes;
}

export function printerTestText(paper: ThermalPaper) {
  return `NILESTOCK PRINTER TEST\n${paper} paper\n${"-".repeat(paper === "58mm" ? 32 : 48)}\nConnection test only.\nNo sale has been recorded.\n\n`;
}

export const RAWBT_STORE = "https://play.google.com/store/apps/details?id=ru.a402d.rawbtprinter";

export function rawbtIntent(bytes: Uint8Array) {
  let binary = "";
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return `intent:base64,${btoa(binary)}#Intent;scheme=rawbt;package=ru.a402d.rawbtprinter;S.browser_fallback_url=${encodeURIComponent(RAWBT_STORE)};end;`;
}
